/** Devolve o termo com acento e inicial maiúscula, pronto para a interface. */
export function termoBonito(termo) {
  const bruto = String(termo || '').trim();
  if (!bruto) return '';

  const palavras = bruto.split(/\s+/).map(p => {
    const chave = p.toLowerCase();
    return ACENTOS[chave] || chave;
  });

  const texto = palavras.join(' ');
  // siglas ficam como estão (SUS, ONU); o resto recebe inicial maiúscula
  if (texto === texto.toUpperCase()) return texto;
  return texto.charAt(0).toUpperCase() + texto.slice(1);
}
